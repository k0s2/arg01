/**
 * 返信情報の取得
 * @param {string} id メールID
 * @returns {Object|undefined} 配列：返信情報
 */
export function getReplyData(id) {
    const group = replyGroups.find(group => group.ids.includes(id));
    return group ? group.reply : [];
}