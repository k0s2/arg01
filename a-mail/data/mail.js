/**
 * メール情報の取得
 * @param {String|String[]} ids 呼び出すメールのID（単数・複数）
 * @returns {Object[]} メール情報の配列
 */
export function getMails(ids) {
    // 単数の場合、配列化
    if (!Array.isArray(ids)) {
        ids = [ids];
    }

    return ids.map(id => mailList.find(mail => mail.id == id)).filter(Boolean);
}